export const TABLE_BY_NAME: ReadonlyMap<string, TableSpec> = new Map(TABLES.map((t) => [t.name, t]));

export function tableSpec(name: string): TableSpec {
  const spec = TABLE_BY_NAME.get(name);
  if (!spec) throw new Error(`unknown table ${name}`);
  return spec;
}

