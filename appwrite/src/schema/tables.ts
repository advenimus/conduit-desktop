const uuid = (nullable = false, extra: Partial<ColumnSpec> = {}): ColumnSpec => ({ type: 'uuid', nullable, ...extra });
const newId = (): ColumnSpec => ({ type: 'uuid', nullable: false, default: { kind: 'uuid' } });
const varchar = (size: number, nullable = true, extra: Partial<ColumnSpec> = {}): ColumnSpec => ({ type: 'varchar', size, nullable, ...extra });
const text = (nullable = true): ColumnSpec => ({ type: 'text', nullable });
const longtext = (nullable = true): ColumnSpec => ({ type: 'longtext', nullable });
const int = (nullable = false, def?: number): ColumnSpec => ({ type: 'int', nullable, ...(def === undefined ? {} : { default: { kind: 'value', value: def } }) });
const float = (nullable = true, def?: number): ColumnSpec => ({ type: 'float', nullable, ...(def === undefined ? {} : { default: { kind: 'value', value: def } }) });
const bool = (def: boolean | undefined, nullable = false): ColumnSpec => ({ type: 'bool', nullable, ...(def === undefined ? {} : { default: { kind: 'value', value: def } }) });
const datetime = (nullable = true): ColumnSpec => ({ type: 'datetime', nullable });
const now = (plusSeconds?: number): ColumnSpec => ({ type: 'datetime', nullable: false, default: { kind: 'now', ...(plusSeconds ? { plusSeconds } : {}) } });
const json = (nullable: boolean, def?: unknown, maxJsonBytes?: number): ColumnSpec => ({
  type: 'json', nullable, ...(def === undefined ? {} : { default: { kind: 'value', value: def } }), ...(maxJsonBytes ? { maxJsonBytes } : {}),
});
const oneOf = (values: readonly string[], def?: string, nullable = false): ColumnSpec => ({
  type: 'varchar', size: 32, nullable, oneOf: values, ...(def === undefined ? {} : { default: { kind: 'value', value: def } }),
});
